void HAL_UART_RxCpltCallback( UART_HandleTypeDef *huart )
{
	BaseType_t xHigherPriorityTaskWoken = pdFALSE;

	if( huart->Instance == USART2 )
	{
		sendCliData();
	}
	else if( huart->Instance == USART6 )
	{
//		GLogN("%02X", gucHSMRxDummy);
		if( xStreamBufferSendFromISR( hSBHsmRx, (void *)&gucHSMRxDummy, 1, &xHigherPriorityTaskWoken ) != 1 )
		{
			GLogE( "Error... fail send HSM streambuffer!!!\r\n" );
		}

		HAL_UART_Receive_IT( huart, &gucHSMRxDummy, 1 );
	}
	else if( huart->Instance == USART1 )
	{
		if( xStreamBufferSendFromISR( hSBKLRx1, (void *)&gucKL1RxDummy, 1, &xHigherPriorityTaskWoken ) != 1 )
		{
			GLogE( "Error... fail send KL Line1 streambuffer!!!\r\n" );
		}

		HAL_UART_Receive_IT( huart, &gucKL1RxDummy, 1 );
	}
	else if( huart->Instance == USART3 )
	{
//		GLogN("%02X", gucKL2RxDummy);
		if( xStreamBufferSendFromISR( hSBKLRx2, (void *)&gucKL2RxDummy, 1, &xHigherPriorityTaskWoken ) != 1 )
		{
			GLogE( "Error... fail send KL Line2 streambuffer!!!\r\n" );
		}

		HAL_UART_Receive_IT( huart, &gucKL2RxDummy, 1 );
	}
	
	portYIELD_FROM_ISR( xHigherPriorityTaskWoken );
}

