/**
  * @brief This function handles DMA1 stream0 global interrupt.
  */
void DMA1_Stream0_IRQHandler(void)
{
  /* USER CODE BEGIN DMA1_Stream0_IRQn 0 */
#if !USE_HW_SPI1_NSS
  /* SPI1 RX DMA TC: CS HIGH with 1us delay (for TransmitReceive_DMA) */
  if ((DMA1->LISR & DMA_LISR_TCIF0) != 0U)
  {
    while ((SPI1->SR & SPI_SR_EOT) == 0U);
    //DWT_DELAY_US(1000);  /* 1us delay before CS HIGH */
    GPIOA->BSRR = SPI1_NSS_Pin;
  }
#endif
  /* USER CODE END DMA1_Stream0_IRQn 0 */
  HAL_DMA_IRQHandler(&hdma_spi1_rx);
  /* USER CODE BEGIN DMA1_Stream0_IRQn 1 */

  /* USER CODE END DMA1_Stream0_IRQn 1 */
}

/**
  * @brief This function handles DMA1 stream1 global interrupt.
  */
void DMA1_Stream1_IRQHandler(void)
{
  /* USER CODE BEGIN DMA1_Stream1_IRQn 0 */
#if !USE_HW_SPI1_NSS
  /* SPI1 TX-only DMA TC: CS HIGH with 1us delay (only for TX-only transfers) */
  if ((DMA1->LISR & DMA_LISR_TCIF1) != 0U)
  {
    /* Check if this is TX-only mode (not TransmitReceive) */
    if (hspi1.State == HAL_SPI_STATE_BUSY_TX)
    {
      while ((SPI1->SR & SPI_SR_EOT) == 0U);
      //DWT_DELAY_US(1);  /* 1us delay before CS HIGH */
      GPIOA->BSRR = SPI1_NSS_Pin;
    }
  }
#endif
  /* USER CODE END DMA1_Stream1_IRQn 0 */
  HAL_DMA_IRQHandler(&hdma_spi1_tx);
  /* USER CODE BEGIN DMA1_Stream1_IRQn 1 */

  /* USER CODE END DMA1_Stream1_IRQn 1 */
}
