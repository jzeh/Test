void OBDCGWAlgorithm()
{
	static bool s_bFirstTime = TRUE;	
	static unsigned int s_uiTimeoutTimer = 0;
	static unsigned char s_ucState=eCGW_None;

	if(s_bFirstTime == TRUE)
	{
		unsigned int uiStartID=0x0700,uiEndID=0x07FF;    
	    unsigned int m_uiStartMask[14],m_uiEndMask[14];

	    memset(&m_uiStartMask,0x00,sizeof(m_uiStartMask));
	    memset(&m_uiEndMask,0x00,sizeof(m_uiEndMask));
		Oem_CAN_None_Receive_Set();

		Oem_CAN_Initial_CH1(Highcan1, eCAN_500KBPS); //init
		Oem_CAN_Channel_Masket_Set(CAN_CHANNEL_1, STANDARD_CAN, 1, &uiStartID, &uiEndID);

		Oem_CAN_Initial_CH2(g_stControlHWSetInfo.m_ucCanChip, g_stControlHWSetInfo.m_ucCanSpeed); //init
		Oem_CAN_Channel_Masket_Set( CAN_CHANNEL_2, STANDARD_CAN, 1, (unsigned int *)m_uiStartMask, (unsigned int *)m_uiEndMask);
		CanBufferClear(eCLEAR_TYPE_ALL);

		s_bFirstTime = FALSE;
		DCAN_SET_COMM_STATE(eCAN_TX_NONE_PARSING);
		LCAN_SET_COMM_STATE(eLCAN_RX_BLOCK);
		s_ucState=eCGW_ExtOpen;
        s_uiTimeoutTimer = Get_Tmr();
	}

	if( DCAN_GET_COMM_STATE() == eCAN_TX_NONE_PARSING )
	{
		if( s_ucState == eCGW_Dummy )	//for car wakeup
		{
			if(VCI_FunctionClassification(eCOMM_UDS_CARBOPEN,0))
			{
				CAN_TxBlockProc();	//실제 REQ
			}
		}
		else if( s_ucState == eCGW_CarbOpen )
		{
			if(VCI_FunctionClassification(eCOMM_UDS_CARBOPEN,0))
			{
				CAN_TxBlockProc();	//실제 REQ
			}
		}
		else if( s_ucState == eCGW_ExtOpen )
		{
			if(VCI_FunctionClassification(eCOMM_UDS_EXTOPEN,0))
			{
				CAN_TxBlockProc();	//실제 REQ
			}
		}
		else if( s_ucState == eCGW_Security1 )
		{
			if(VCI_FunctionClassification(eCOMM_CGW_SECURITY1,0))
			{
				CAN_TxBlockProc();	//실제 REQ
			}
		}
		else if( s_ucState == eCGW_Security2 )
		{
			if(VCI_FunctionClassification(eCOMM_CGW_SECURITY2,0))
			{
				CAN_TxBlockProc();	//실제 REQ
			}
		}
		else
		{
		}
        if( Get_TmrDelta(Get_Tmr(),s_uiTimeoutTimer) >= CGW_TIMEOUT_TIME )
		{
			DCAN_SET_COMM_STATE(eCAN_TX_NONE_PARSING);
			SetOBDState(eOBD_Running_Info_Mode);
			s_bFirstTime = TRUE;
			if(CFD_GetCanFDAdapter())
			{
				CFD_SetByPassFlagAllOn();			
			}
		}
	}
	else
	{
		if( Get_TmrDelta(Get_Tmr(),s_uiTimeoutTimer) >= CGW_TIMEOUT_TIME )
		{
			DCAN_SET_COMM_STATE(eCAN_TX_NONE_PARSING);
			SetOBDState(eOBD_Running_Info_Mode);
			s_bFirstTime = TRUE;
			if(CFD_GetCanFDAdapter())
			{
				CFD_SetByPassFlagAllOn();			
			}
		}
		else
		{
			CAN_TxBlockProc();	//실제 REQ
			if( DCAN_GET_COMM_STATE() >= eCAN_RX_FAIL )	//성공하거나 실패할경우 다음 REQ
			{
                if( DCAN_GET_COMM_STATE() == eCAN_RX_FAIL)
                {
                     if( s_ucState == eCGW_Dummy )
                     {
                         DCAN_SET_COMM_STATE(eCAN_TX_NONE_PARSING);
                         s_ucState++;
                     }
                     else
                     {
                    SetOBDState(eOBD_Running_Info_Mode);
                    s_bFirstTime = TRUE;
                    if(CFD_GetCanFDAdapter())
                    {
                        CFD_SetByPassFlagAllOn();			
                    }
                    DCAN_SET_COMM_STATE(eCAN_TX_NONE_PARSING);
                }
                }
                else
                {
                    s_ucState++;

                    if( s_ucState == eCGW_SecurityDone )
                    {
                        SetOBDState(eOBD_Running_Info_Mode);
                        s_bFirstTime = TRUE;
                        if(CFD_GetCanFDAdapter())
                        {
                            CFD_SetByPassFlagAllOn();			
                        }
                    }
                    DCAN_SET_COMM_STATE(eCAN_TX_NONE_PARSING);
                }
			}
		}
	}
}

